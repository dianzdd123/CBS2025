import cv2
import numpy as np
import pandas as pd
import pywt
from pathlib import Path
import argparse

# Function to process frames and apply contour detection
def process_frame(frame):
    gray_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    blurred_frame = cv2.GaussianBlur(gray_frame, (5, 5), 0)
    adaptive_thresh = cv2.adaptiveThreshold(blurred_frame, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                                            cv2.THRESH_BINARY_INV, 11, 2)
    edges = cv2.Canny(adaptive_thresh, 50, 150)
    kernel = np.ones((5, 5), np.uint8)
    closing = cv2.morphologyEx(edges, cv2.MORPH_CLOSE, kernel)
    contours, _ = cv2.findContours(closing, cv2.RETR_TREE, cv2.CHAIN_APPROX_SIMPLE)
    return contours, gray_frame

# Function to process frames for focus measures
def process_gray_frame(frame):
    gray_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    blurred_frame = cv2.GaussianBlur(gray_frame, (5, 5), 0)
    resized_frame = cv2.resize(blurred_frame, (256, 256))
    return resized_frame

# Define focus measure functions
def laplacian_of_gaussian(image):
    return cv2.Laplacian(image, cv2.CV_64F).var()

def tenengrad(image):
    sobel_x = cv2.Sobel(image, cv2.CV_64F, 1, 0, ksize=3)
    sobel_y = cv2.Sobel(image, cv2.CV_64F, 0, 1, ksize=3)
    gradient_magnitude = np.sqrt(sobel_x**2 + sobel_y**2)
    return np.mean(gradient_magnitude)

def brenner(image):
    image = np.asarray(image, dtype=np.float64)  # Avoid uint8 subtraction/square overflow.
    shifted_image = np.roll(image, -2, axis=1)
    return np.sum((image[:, :-2] - shifted_image[:, :-2])**2)

def gray_level_variance(image):
    return np.var(image)

def entropy(image):
    histogram = cv2.calcHist([image], [0], None, [256], [0, 256])
    histogram = histogram / histogram.sum()
    entropy_value = -np.sum(histogram * np.log2(histogram + 1e-10))
    return entropy_value

def wavelet_focus_measure(image):
    coeffs = pywt.wavedec2(image, 'db1', level=4)
    return sum(np.sum(np.abs(coeff)) for coeff in coeffs[1:])

def max_absolute_gradient(image):
    sobel_x = cv2.Sobel(image, cv2.CV_64F, 1, 0, ksize=3)
    sobel_y = cv2.Sobel(image, cv2.CV_64F, 0, 1, ksize=3)
    return np.max(np.abs(sobel_x) + np.abs(sobel_y))

focus_functions = [
    laplacian_of_gaussian,
    tenengrad, brenner,
    gray_level_variance,
    entropy, wavelet_focus_measure,
    max_absolute_gradient
]

# Segment image into smaller grids
def segment_image(image, grid_size):
    segments = []
    h, w = image.shape
    step_h, step_w = h // grid_size[0], w // grid_size[1]
    for i in range(grid_size[0]):
        for j in range(grid_size[1]):
            segment = image[i*step_h:(i+1)*step_h, j*step_w:(j+1)*step_w]
            segments.append(segment)
    return segments

# Extract local features from segmented image
def extract_local_features(image, grid_size, focus_functions):
    segments = segment_image(image, grid_size)
    features = []
    for segment in segments:
        features.extend([func(segment) for func in focus_functions])
    return features

# Function to process video and extract features
def process_video(video_path, focus_functions, bbox_width=300, bbox_height=300, grid_size=(6, 6)):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        cap.release()
        raise ValueError(f"Could not open video: {video_path}")

    processed_frames = []
    focus_features = []

    frame_count = 0  # Initialise frame count for debugging

    while True:
        ret, frame = cap.read()
        if not ret:
            print("End of video or error reading frame.")
            break

        frame_count += 1  # Increment frame count
        print(f"Processing frame {frame_count}")  # Debug print

        contours, gray_frame = process_frame(frame)

        max_area = 0
        main_contour = None
        frame_area = frame.shape[0] * frame.shape[1]

        for contour in contours:
            area = cv2.contourArea(contour)
            if 0.01 * frame_area < area < 0.9 * frame_area:
                if area > max_area:
                    max_area = area
                    main_contour = contour

        if main_contour is not None:
            x, y, w, h = cv2.boundingRect(main_contour)
            center_x, center_y = x + w // 2, y + h // 2
            start_x = max(center_x - bbox_width // 2, 0)
            start_y = max(center_y - bbox_height // 2, 0)
            end_x = min(center_x + bbox_width // 2, frame.shape[1])
            end_y = min(center_y + bbox_height // 2, frame.shape[0])
            cropped_frame = frame[start_y:end_y, start_x:end_x]
            cropped_frame = cv2.resize(cropped_frame, (350, 350))

            gray_cropped_frame = process_gray_frame(cropped_frame)
            processed_frames.append(gray_cropped_frame)

            features = extract_local_features(gray_cropped_frame, grid_size, focus_functions)
            focus_features.append(features)

    cap.release()

    return processed_frames, focus_features

def main(argv=None):
    """Extract one CSV per video; no Drive mount or training runs on import."""
    parser = argparse.ArgumentParser(description="Extract local focus features from microrobot videos.")
    parser.add_argument("videos", nargs="+", type=Path, help="Input video files, in the desired order.")
    parser.add_argument("--output-dir", type=Path, required=True, help="Directory for per-video feature CSV files.")
    args = parser.parse_args(argv)
    for video in args.videos:
        if not video.is_file():
            parser.error(f"Video does not exist: {video}")
    destinations = [args.output_dir / (video.stem + "_focus_features.csv") for video in args.videos]
    if len(set(destinations)) != len(destinations):
        parser.error("Videos must have distinct filename stems to avoid output collisions.")
    if any(path.exists() for path in destinations):
        parser.error("An output CSV already exists; choose another output directory.")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for video, output in zip(args.videos, destinations):
        _, features = process_video(str(video), focus_functions)
        if not features:
            raise ValueError(f"No contour-qualified frames found in {video}")
        pd.DataFrame(features).to_csv(output, index=False)
        print(f"Saved {len(features)} rows to {output}")


if __name__ == "__main__":
    main()
