import pandas as pd
import joblib
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, r2_score
import os

# Paths to the files
features_path = '/content/drive/MyDrive/df_local_focus_measures_5.csv'
target_path = '/content/drive/MyDrive/df_values5.csv'
model_path = '/content/drive/MyDrive/simpler_xgb_model_4.pkl'

# Load the trained model
if os.path.isfile(model_path):
    best_model = joblib.load(model_path)
    print("Model loaded successfully.")
else:
    print(f"Model file does not exist: {model_path}")
    exit()

# Load the features data
if os.path.isfile(features_path):
    df_features = pd.read_csv(features_path)
    print("Features data loaded successfully.")
else:
    print(f"Features data file does not exist: {features_path}")
    exit()

# Load the target data
if os.path.isfile(target_path):
    df_target = pd.read_csv(target_path, header=None)
    print("Target data loaded successfully.")
else:
    print(f"Target data file does not exist: {target_path}")
    exit()

# Extract the 'Value' column and drop NaN values
actual_depth = df_target[0].dropna().values

# Make predictions using the loaded model
predictions = best_model.predict(df_features)

# Calculate MSE and R² score
mse = mean_squared_error(actual_depth, predictions)
r2 = r2_score(actual_depth, predictions)
print(f"Mean Squared Error: {mse}")
print(f"R² Score: {r2}")

# Normalize the actual depth and predictions
scaler = MinMaxScaler()

# Reshape data to fit the scaler
actual_depth_normalized = scaler.fit_transform(actual_depth.reshape(-1, 1)).flatten()
predictions_normalized = scaler.transform(predictions.reshape(-1, 1)).flatten()

# Plot normalized predictions vs. actual depth data with MSE and R² score
plt.figure(figsize=(12, 6))
plt.plot(actual_depth_normalized, label='Actual Depth (Normalized)', color='blue', marker='o')
plt.plot(predictions_normalized, label='Predictions (Normalized)', color='red', linestyle='--')
plt.title('Local features: Normalized Predictions vs. Actual Depth Data')
plt.xlabel('Sample Index')
plt.ylabel('Normalized Depth')
plt.legend()
plt.figtext(0.15, 0.85, f'MSE: {mse:.4f}', fontsize=12, color='black')
plt.figtext(0.15, 0.80, f'R²: {r2:.4f}', fontsize=12, color='black')
plt.tight_layout()
plt.show()